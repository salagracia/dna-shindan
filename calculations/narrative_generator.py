def is_sara(user_data: dict) -> bool:
    """ユーザーがサラさん本人かを判定（テスト用本文の出し分け）"""
    kana = (user_data.get('name_kana') or '').replace(' ', '').replace('　', '')
    name = (user_data.get('name') or '').replace(' ', '').replace('　', '')
    return kana == 'ヤマオカサラ' or name == '山岡サラ'


